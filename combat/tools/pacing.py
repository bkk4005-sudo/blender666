"""Shared authored pacing for editable Blender poses and server timelines.

Frame numbers describe this project, not DS3 source frames. Runtime playback
stays at speed 1; independently retimed phases are baked into the actual Actions.
"""
import json
from pathlib import Path

COMBAT = Path(__file__).resolve().parents[1]
PACING = json.loads((COMBAT / "config/action_pacing.json").read_text())
FPS = PACING["authoringFPS"]


def runtime_actions():
    actions = {}
    for name, clip in PACING["clips"].items():
        if name in ("CombatIdle", "Block"):
            continue
        fields = {"duration": clip["durationFrame"] / FPS}
        for key, value in clip.get("runtimeFrames", {}).items():
            fields[key] = [v / FPS for v in value] if isinstance(value, list) else value / FPS
        fields.update(clip.get("runtimeValues", {}))
        actions[name] = fields
    return actions


def pace_clip(clip):
    timing = PACING["clips"][clip["name"]]
    mapping = dict(timing["poseFrames"])
    old_frames = [round(t * FPS) for t, _ in clip["keys"]]
    assert len(old_frames) == len(mapping) and set(old_frames) == set(mapping), (clip["name"], old_frames)
    new_frames = [mapping[frame] for frame in old_frames]
    assert new_frames[0] == 0 and new_frames[-1] == timing["durationFrame"]
    assert all(a < b for a, b in zip(new_frames, new_frames[1:]))
    clip["keys"] = [(new / FPS, posture) for new, (_, posture) in zip(new_frames, clip["keys"])]
    clip["duration"] = timing["durationFrame"] / FPS
    clip["markers"] = {name: frame / FPS for name, frame in timing["markers"].items()}
    clip["groundedFrames"] = timing.get("groundedFrames")
    return clip


def luau(value):
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{key} = {luau(v)}" for key, v in value.items()) + " }"
    if isinstance(value, list):
        return "{ " + ", ".join(luau(v) for v in value) + " }"
    if isinstance(value, str):
        return json.dumps(value)
    return format(value, ".12g")


def write_runtime():
    actions = runtime_actions()
    text = "-- Generated by tools/pacing.py from config/action_pacing.json.\n"
    text += "-- Authored project tuning; not measured Dark Souls III timings.\nreturn {\n"
    text += f"    Version = {luau(PACING['version'])},\n"
    text += f"    Movement = {luau(PACING['movement'])},\n    Actions = {{\n"
    text += "\n".join(f"        {name} = {luau(fields)}," for name, fields in actions.items())
    text += "\n    },\n}\n"
    (COMBAT / "src/shared/CombatPacing.luau").write_text(text, encoding="utf-8")


if __name__ == "__main__":
    write_runtime()
    print("Generated", PACING["version"], "pacing for", len(PACING["clips"]), "clips")
